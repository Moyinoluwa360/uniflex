import 'dart:convert';

import 'package:flutter/material.dart';
import 'package:webview_flutter/webview_flutter.dart';

/// Full-screen page that renders the Paystack Popup JS checkout inside a
/// native WebView. The caller pushes this as a modal route and awaits the
/// result — a non-null [String] is the Paystack reference on success,
/// [null] means the user cancelled or an error occurred.
///
/// Only the public key is loaded here. The secret key never leaves the
/// Edge Function (`verify-paystack-payment`).
class PaystackCheckoutPage extends StatefulWidget {
  const PaystackCheckoutPage({
    super.key,
    required this.publicKey,
    required this.email,
    required this.amountNaira,
    required this.reference,
  });

  final String publicKey;
  final String email;

  /// Amount in Naira (₦). Converted to kobo (× 100) when passed to Paystack.
  final double amountNaira;

  /// A unique reference generated by the caller. This same reference is
  /// later sent to the Edge Function for server-side verification.
  final String reference;

  @override
  State<PaystackCheckoutPage> createState() => _PaystackCheckoutPageState();
}

class _PaystackCheckoutPageState extends State<PaystackCheckoutPage> {
  late final WebViewController _controller;
  String? _error;

  @override
  void initState() {
    super.initState();
    _initWebView();
  }

  void _initWebView() {
    _controller = WebViewController()
      ..setJavaScriptMode(JavaScriptMode.unrestricted)
      ..setBackgroundColor(Colors.white)
      ..addJavaScriptChannel(
        'PaystackChannel',
        onMessageReceived: _onPaystackMessage,
      )
      ..setNavigationDelegate(
        NavigationDelegate(
          onWebResourceError: (err) {
            setState(() {
              _error = 'Failed to load payment page (${err.description})';
            });
          },
        ),
      )
      ..loadHtmlString(_buildPaystackHtml());
  }

  void _onPaystackMessage(JavaScriptMessage message) {
    try {
      final data = json.decode(message.message) as Map<String, dynamic>;
      final status = data['status'] as String?;

      if (status == 'success') {
        final ref = data['reference'] as String?;
        Navigator.of(context).pop(ref);
      } else {
        // Cancelled or failed
        Navigator.of(context).pop(null);
      }
    } catch (_) {
      Navigator.of(context).pop(null);
    }
  }

  String _buildPaystackHtml() {
    // Escape values to prevent XSS within the inline script.
    // These values come from our own backend (email from profile, public
    // key from .env, reference we generated) — they are not user-typed.
    final safeKey = _escapeJs(widget.publicKey);
    final safeEmail = _escapeJs(widget.email);
    final amountKobo = (widget.amountNaira * 100).round();
    final safeRef = _escapeJs(widget.reference);

    return '''
<!DOCTYPE html>
<html>
<head>
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;
      background: #f5f6f5;
      display: flex;
      align-items: center;
      justify-content: center;
      min-height: 100vh;
    }
    .loader {
      text-align: center;
      color: #555;
    }
    .spinner {
      width: 40px; height: 40px;
      border: 3px solid #eee;
      border-top-color: #10b981;
      border-radius: 50%;
      animation: spin 0.8s linear infinite;
      margin: 0 auto 16px;
    }
    @keyframes spin { to { transform: rotate(360deg); } }
  </style>
</head>
<body>
  <div class="loader">
    <div class="spinner"></div>
    <p>Loading payment…</p>
  </div>
  <script src="https://js.paystack.co/v1/inline.js"></script>
  <script>
    window.onload = function () {
      var handler = PaystackPop.setup({
        key: '$safeKey',
        email: '$safeEmail',
        amount: $amountKobo,
        ref: '$safeRef',
        currency: 'NGN',
        label: 'Uniflex Wallet Top-up',
        onClose: function () {
          PaystackChannel.postMessage(JSON.stringify({ status: 'cancelled' }));
        },
        callback: function (response) {
          PaystackChannel.postMessage(
            JSON.stringify({ status: 'success', reference: response.reference })
          );
        }
      });
      handler.openIframe();
    };
  </script>
</body>
</html>
''';
  }

  /// Escapes a string for safe embedding in a single-quoted JS literal.
  String _escapeJs(String s) =>
      s.replaceAll(r'\', r'\\').replaceAll("'", r"\'");

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    return Scaffold(
      appBar: AppBar(
        title: const Text('Fund Wallet'),
        leading: IconButton(
          icon: const Icon(Icons.close),
          tooltip: 'Cancel',
          onPressed: () => Navigator.of(context).pop(null),
        ),
      ),
      // Exactly one loading state is ever visible: the WebView shows its
      // own inline spinner (see _buildPaystackHtml) while Paystack's SDK
      // loads, then Paystack's own popup takes over — no separate native
      // spinner is layered on top of either (Section 4 of the
      // post-testing fixes: this used to stack three loaders at once).
      body: _error != null
          ? Center(
              child: Padding(
                padding: const EdgeInsets.all(24),
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Icon(Icons.error_outline,
                        size: 48,
                        color: theme.colorScheme.error),
                    const SizedBox(height: 16),
                    Text(
                      _error!,
                      textAlign: TextAlign.center,
                      style: theme.textTheme.bodyMedium,
                    ),
                    const SizedBox(height: 24),
                    TextButton(
                      onPressed: () => Navigator.of(context).pop(null),
                      child: const Text('Go back'),
                    ),
                  ],
                ),
              ),
            )
          : WebViewWidget(controller: _controller),
    );
  }
}
