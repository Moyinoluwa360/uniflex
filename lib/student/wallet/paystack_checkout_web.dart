import 'dart:async';
import 'dart:convert';
// ignore: avoid_web_libraries_in_flutter, deprecated_member_use
import 'dart:html' as html;

import 'package:flutter/material.dart';

import '../../shared/theme/app_colors.dart';
import '../../shared/widgets/app_bar/uniflex_app_bar.dart';

/// Web implementation of the Paystack checkout flow.
///
/// `webview_flutter` does not support Flutter web, so instead we:
///   1. Inject Paystack's inline.js into the browser document (once).
///   2. Inject a small script that calls PaystackPop.setup().openIframe() —
///      Paystack renders its own overlay directly in the browser DOM, on top
///      of Flutter's canvas.
///   3. The JS callbacks dispatch a `CustomEvent` whose `detail` is a
///      JSON string, which Dart picks up via dart:html without needing
///      dart:js / dart:js_interop at all.
///
/// The interface (constructor, return type) is identical to the native
/// version so wallet_screen.dart needs no changes.
class PaystackCheckoutPage extends StatefulWidget {
  const PaystackCheckoutPage({
    super.key,
    required this.publicKey,
    required this.email,
    required this.amountNaira,
    required this.reference,
    required this.userId,
  });

  final String publicKey;
  final String email;

  /// Metadata forwarded to Paystack and later read by the verify Edge Function.
  final String userId;

  /// Amount in Naira — converted to kobo (×100) before passing to Paystack.
  final double amountNaira;

  /// Unique reference generated by the caller; sent to the verify Edge
  /// Function after a successful checkout.
  final String reference;

  @override
  State<PaystackCheckoutPage> createState() => _PaystackCheckoutPageState();
}

class _PaystackCheckoutPageState extends State<PaystackCheckoutPage> {
  _Phase _phase = _Phase.loading;
  String? _error;
  StreamSubscription<html.Event>? _resultSub;

  @override
  void initState() {
    super.initState();
    _loadAndOpen();
  }

  @override
  void dispose() {
    _resultSub?.cancel();
    super.dispose();
  }

  // ── Boot sequence ────────────────────────────────────────────────────────────

  Future<void> _loadAndOpen() async {
    try {
      await _ensurePaystackSdkLoaded();
      if (!mounted) return;
      _openCheckout();
    } catch (e) {
      if (mounted) {
        setState(() {
          _phase = _Phase.error;
          _error = 'Could not load Paystack ($e). Please try again.';
        });
      }
    }
  }

  /// Injects `https://js.paystack.co/v1/inline.js` the first time; skips if
  /// already present (e.g. user opened the checkout page more than once).
  Future<void> _ensurePaystackSdkLoaded() async {
    // If PaystackPop is already in window scope, nothing to do.
    // We test for an existing <script> tag rather than checking JS globals
    // (which would require dart:js).
    final existing = html.document
        .querySelectorAll('script[data-uniflex-paystack]');
    if (existing.isNotEmpty) {
      // Give the script a moment to fully initialise if it was just injected.
      await Future<void>.delayed(const Duration(milliseconds: 200));
      return;
    }

    final completer = Completer<void>();
    final script = html.ScriptElement()
      ..src = 'https://js.paystack.co/v1/inline.js'
      ..async = true
      ..setAttribute('data-uniflex-paystack', '1');

    late StreamSubscription<html.Event> loadSub;
    late StreamSubscription<html.Event> errSub;

    loadSub = script.onLoad.listen((_) {
      loadSub.cancel();
      errSub.cancel();
      completer.complete();
    });
    errSub = script.onError.listen((_) {
      loadSub.cancel();
      errSub.cancel();
      completer.completeError('Paystack script failed to load');
    });

    html.document.head!.append(script);
    await completer.future;
  }

  /// Injects a one-shot <script> that calls PaystackPop.setup().openIframe().
  /// Callbacks dispatch a CustomEvent whose detail is a JSON string so Dart
  /// can read it purely via dart:html.
  void _openCheckout() {
    final amountKobo = (widget.amountNaira * 100).round();
    final safeKey = _escapeJs(widget.publicKey);
    final safeEmail = _escapeJs(widget.email);
    final safeRef = _escapeJs(widget.reference);
    final safeUserId = _escapeJs(widget.userId);

    // Listen for the result event BEFORE injecting the script so we never
    // miss it. The subscription is cancelled after the first event.
    _resultSub = html.window.on['_uniflex_paystack_done'].listen(_onResult);

    final invokeScript = html.ScriptElement()
      ..text = '''
(function () {
  var handler = PaystackPop.setup({
    key: '$safeKey',
    email: '$safeEmail',
    amount: $amountKobo,
    ref: '$safeRef',
    currency: 'NGN',
    label: 'Uniflex Wallet Top-up',
    metadata: { user_id: '$safeUserId' },
    onClose: function () {
      window.dispatchEvent(new CustomEvent('_uniflex_paystack_done', {
        detail: JSON.stringify({ status: 'cancelled' })
      }));
    },
    callback: function (response) {
      window.dispatchEvent(new CustomEvent('_uniflex_paystack_done', {
        detail: JSON.stringify({ status: 'success', reference: response.reference })
      }));
    }
  });
  handler.openIframe();
})();
''';

    html.document.head!.append(invokeScript);
    // The script executes synchronously once appended; remove the element
    // immediately to keep the DOM clean.
    invokeScript.remove();

    if (mounted) setState(() => _phase = _Phase.awaitingPopup);
  }

  void _onResult(html.Event event) {
    _resultSub?.cancel();
    _resultSub = null;
    if (!mounted) return;

    try {
      final customEvent = event as html.CustomEvent;
      final data =
          json.decode(customEvent.detail as String) as Map<String, dynamic>;
      final status = data['status'] as String?;

      if (status == 'success') {
        Navigator.of(context).pop(data['reference'] as String?);
      } else {
        Navigator.of(context).pop(null);
      }
    } catch (_) {
      Navigator.of(context).pop(null);
    }
  }

  // ── Helpers ─────────────────────────────────────────────────────────────────

  /// Escapes a value for safe embedding in a single-quoted JS string literal.
  String _escapeJs(String s) =>
      s.replaceAll(r'\', r'\\').replaceAll("'", r"\'");

  // ── UI ───────────────────────────────────────────────────────────────────────

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);

    return Scaffold(
      appBar: UniflexAppBar(
        title: 'Fund Wallet',
        leading: IconButton(
          icon: const Icon(Icons.close),
          tooltip: 'Cancel',
          onPressed: () => Navigator.of(context).pop(null),
        ),
      ),
      body: switch (_phase) {
        _Phase.loading => const Center(child: CircularProgressIndicator()),
        _Phase.error => Center(
            child: Padding(
              padding: const EdgeInsets.all(24),
              child: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Icon(Icons.error_outline,
                      size: 48, color: theme.colorScheme.error),
                  const SizedBox(height: 16),
                  Text(_error!,
                      textAlign: TextAlign.center,
                      style: theme.textTheme.bodyMedium),
                  const SizedBox(height: 24),
                  TextButton(
                    onPressed: () => Navigator.of(context).pop(null),
                    child: const Text('Go back'),
                  ),
                ],
              ),
            ),
          ),
        _Phase.awaitingPopup => Center(
            child: Padding(
              padding: const EdgeInsets.all(32),
              child: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  const SizedBox(
                    width: 48,
                    height: 48,
                    child: CircularProgressIndicator(strokeWidth: 2),
                  ),
                  const SizedBox(height: 24),
                  Text(
                    'Complete your payment in the Paystack popup.',
                    textAlign: TextAlign.center,
                    style: theme.textTheme.bodyMedium,
                  ),
                  const SizedBox(height: 8),
                  Text(
                    'If the popup did not appear, check that your browser\n'
                    'is not blocking popups for this site.',
                    textAlign: TextAlign.center,
                    style: theme.textTheme.bodySmall?.copyWith(
                      color:
                          theme.colorScheme.onSurface.withValues(alpha: 0.55),
                    ),
                  ),
                  const SizedBox(height: 32),
                  TextButton.icon(
                    onPressed: () => Navigator.of(context).pop(null),
                    icon: const Icon(Icons.close,
                        size: 16, color: AppColors.error),
                    label: const Text('Cancel',
                        style: TextStyle(color: AppColors.error)),
                  ),
                ],
              ),
            ),
          ),
      },
    );
  }
}

enum _Phase { loading, awaitingPopup, error }
